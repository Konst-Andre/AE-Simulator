/* ═══════════════════════════════════════════════════════════════════
   AE-Simulator · проксі до Groq
   живе доки: доки застосунок ходить у модель не напряму

   Що робить:
     1. пускає тільки свої домени (Origin) і тільки зі знанням кодового слова
     2. ховає ключ Groq — він у секретах, у браузер не потрапляє
     3. складає тіло запиту САМ: модель і межі бере звідси, не з браузера
     4. драбина моделей — квота вичерпана або модель зникла → наступна сходинка
     5. каже українською, коли не може відповісти
     6. пін: заголовок x-ae-pin із НОМЕРОМ сходинки притискає запит до неї
        (режим перевірки; назву моделі браузер не називає ніколи)
     7. роль обирає, з якої сходинки драбина СТАРТУЄ: клієнт і суддя не
        діляться одним хвилинним відром токенів (див. «ХВИЛИННЕ ВІДРО»)

   Чого НЕ робить (свідомо):
     · не рахує запити — на free tier стелю тримає сам Groq, дубль не додає захисту
     · не тримає стану — ні KV, ні лічильників. Це крок 5 (Куратор)

   Секрети (Cloudflare → Settings → Variables):
     GROQ_KEY     ключ Groq. Encrypt.
     AE_CODE      кодове слово мережі, одне на всіх. Encrypt.
     AE_ORIGINS   дозволені домени через кому, БЕЗ слеша в кінці. Plain text.
                  напр: https://konst-andre.github.io,https://ae.pages.dev

   Деплой: Cloudflare → Workers → Create → Edit code → вставити цей файл.
   Після переїзду на Pages: покласти як functions/api/chat.js і замінити
   останній блок на:  export const onRequestPost = c => handle(c.request, c.env);
   ═══════════════════════════════════════════════════════════════════ */

/* ── ХВИЛИННЕ ВІДРО ───────────────────────────────────────────────────
   Groq рахує TPM (токени за хвилину) ОКРЕМО НА КОЖНУ МОДЕЛЬ, а не на
   акаунт. Текст відмови називає модель прямо: «Rate limit reached for
   model … Limit 8000, Used 6627». Це вимірювальний факт із логів живого
   прогону, не припущення з документації.

   Наслідок: доки клієнт і суддя їхали на одній моделі, вони ділили одне
   відро. Остання репліка клієнта ≈3,3 тис. токенів, суддя ≈3,4–4,8 тис.,
   і стартує він у ту саму хвилину — сума 7–8 тис. проти стелі 8 тис.
   Розбір падав саме там, де він потрібен: у кінці розмови.

   Тому роль тепер обирає СТАРТ драбини (поле `first`). Різні моделі —
   різні відра, перетин зникає арифметично, без різання критеріїв судді
   й без гіпотез про кешування префікса.
   ─────────────────────────────────────────────────────────────────── */

/* ── ДРАБИНА ──────────────────────────────────────────────────────────
   Порядок: спершу найближчі за поведінкою, потім найстійкіші.
   Preview-моделі Groq знімає з коротким попередженням — тому дві останні
   сходинки Production, вони і є страховка від зникнення, а не від квоти.

   ⚠ ПОРЯДОК СХОДИНОК НЕ ПЕРЕСТАВЛЯТИ. Браузер вивчає назви моделей у
   localStorage.ae_rung_names під НОМЕРОМ сходинки. Перестановка не
   червоніє ніде — вона просто змушує екран якийсь час підписувати чипи
   чужими назвами. Роль обирає старт полем `first`, не порядком: щоб
   змінити, з чого стартує суддя, порядок чіпати не треба.

   tested: false = сходинка ВИМКНЕНА. Вмикати тільки після живого прогону
   сценарію на ній: неперевірена сходинка не рятує, а мовчки підміняє
   продукт іншим (клієнт може заговорити російською, і це виглядатиме
   як робота, а не як поломка).
   Обійти прапорець має право РІВНО ОДИН механізм — пін сходинки
   (заголовок x-ae-pin, режим перевірки). Платить він тим, що в
   пінованому режимі запасу немає: список із однієї сходинки, тож 429
   видно як помилку, а не як тиху заміну. Іншого обходу немає.

   first: яка роль СТАРТУЄ з цієї сходинки. Рівно одна сходинка на роль,
   і це мусять бути різні сходинки — інакше повертається спільне відро.
   Порожній масив = сходинка тільки як запас. Стереже smoke_step3.
   ─────────────────────────────────────────────────────────────────── */
/* ДВІ РОЛІ, ДВА ПРОФІЛІ.
   Клієнту роздуми потрібні, але дешеві. Спершу тут стояв 'none' — гіпотеза
   була, що жива людина відповідає рефлекторно і швидкість робить її схожою
   на людину. Живий прогін (крок Ж-3) показав протилежне: без роздумів клієнт
   не зважує аргумент фармацевта, а просто тримає позицію. З 'low' відповіді
   стали помітно доречнішими, тому сходинка 0 переведена на 'low'.
   Суддя робить іншу роботу: звіряє, що сталось, із числами. Тому effort і
   стеля токенів залежать від ролі, яку браузер називає заголовком x-ae-role.

   ⚠ ПАРА ОБОВ'ЯЗКОВА: роздуми рахуються в ту саму стелю, тому будь-який
   effort, крім 'none', вимагає tokens >= 800. Розірвеш пару — JSON обірветься
   на півслові, і людина побачить «відповідь не читається» замість репліки.
   Це стереже smoke_step3 по ВСІХ сходинках, не лише активній.

   ⚠ У РЕЖИМІ СХЕМИ ОБРІЗАНОЇ ВІДПОВІДІ НЕ ІСНУЄ. Коли запит іде з
   json_schema, постачальник перевіряє готовий JSON і на обрізаному віддає
   400 json_validate_failed — не «трохи менше тексту», а порожнечу. Тому
   стелю судді треба брати під НАЙГІРШУ розмову, не під медіанну.
   Виміряно на живих прогонах: розбір коротких розмов — 429 і 541 токен
   виходу (200 OK), розбір розмови на шість реплік уперся в 1100 і згорів,
   розбір розмови на сім реплік узяв **1978** і вклався у 2000 із запасом
   у 22 токени. Тобто 2000 не було межею — воно було майже межею, а
   «майже» в режимі схеми коштує весь розбір.
   Звідси tokens.judge = 3000: півтора рази від найбільшого спостереженого.
   Розкид тут великий саме через роздуми: у 1978 токенах виходу тексту
   розбору ~450, решта — прихований ланцюжок `medium`, і його довжина
   росте з довжиною розмови, а не з довжиною відповіді.
   Вхід судді ≈3,8 тис., тож 3,8 + 3,0 = 6,8 тис. лишається під стелею
   TPM 8 тис. на своїй моделі.

   `reasoning_format:'hidden'` мислення НЕ вимикає — він лише не повертає
   ланцюжок у відповіді. Вимикає його саме effort 'none'.
   Які значення effort приймає конкретна модель — див. EFFORT_OK нижче.

   Роль приходить ІЗ БРАУЗЕРА, але значення бере воркер зі свого списку:
   чужий запит не може попросити 'high' і вигребти квоту роздумами. */
const LADDER = [
  { model: 'qwen/qwen3.8-27b',    tested: true,  first: ['client'],
    reasoning_format: 'hidden',
    effort: { client: 'low',  judge: 'medium' }, tokens: { client: 800, judge: 3000 } },
  /* qwen3.6 приймає лише none | default (факт: провайдер відмовив на 'low',
     див. EFFORT_OK). З 'default' модель з'їдає всю стелю роздумами: у логах
     400 із виходом рівно 800 при стелі 800 — JSON не дописався, і схему
     завернуло як json_validate_failed. Під нашою стелею (LIM.maxTokens 1200)
     ця сходинка живе тільки з вимкненими роздумами. Лишається вимкненою,
     доки не пройде живий сценарій на піні. */
  { model: 'qwen/qwen3.6-27b',    tested: false, first: [],
    reasoning_format: 'hidden',
    effort: { client: 'none', judge: 'none' },   tokens: { client: 800, judge: 3000 } },
  /* Старт судді. Живий прогін: сходинка тримає схему і відповідає стабільно
     — але у ролі КЛІЄНТА. У ролі судді її ще не бачив ніхто: розбір щоразу
     зрізав 429 спільного відра. Ціна ввімкнення названа тут, а не в самері:
     перший же розбір після цієї збірки і є її перевірка. */
  { model: 'openai/gpt-oss-120b', tested: true,  first: ['judge'],
    reasoning_format: 'hidden',
    effort: { client: 'low',  judge: 'medium' }, tokens: { client: 800, judge: 3000 } },
  /* Запас для обох ролей. Той самий живий прогін, та сама ціна. */
  { model: 'openai/gpt-oss-20b',  tested: true,  first: [],
    reasoning_format: 'hidden',
    effort: { client: 'low',  judge: 'medium' }, tokens: { client: 800, judge: 3000 } }
];

/* ── ДОЗВОЛЕНІ ЗНАЧЕННЯ effort, ПО МОДЕЛЯХ ────────────────────────────
   Перелік приймальних значень у постачальника РІЗНИЙ для різних моделей,
   і невідповідність він повертає кодом 400 — а 400 драбиною не сходить
   (і не повинен: помилка змісту однакова на всіх сходинках). Тобто
   сходинка з чужим значенням не «працює гірше», вона вбиває запит.

   Саме це й ховалось до піна: сходинка 1 стояла на 'low', якого qwen3.6
   не приймає. Драбина її не викликала, поки жива основна, тож дефект був
   невидимий — а спрацював би рівно в момент вичерпання квоти, тобто
   замість страховки віддав би людині нечитабельну помилку.

   Звідки значення: qwen3.6 — з тексту відмови провайдера (жорсткий факт).
   gpt-oss і qwen3.8 — з документації постачальника; на 'low' обидві
   відповіли 200 у живому прогоні, 'medium' у ролі судді фактом ще НЕ
   підтверджений. Тобто цей перелік ловить не все: він ловить значення,
   про які ми вже знаємо, що вони чужі.

   Споживачів двоє: гейт smoke_step3 (перевіряє драбину до деплою) і сам
   воркер нижче (перевіряє її ще раз у момент запиту — бо цей файл
   деплоїться руками в дашборді й гейт над деплоєм не стоїть).

   ⚠ ПОРЯДОК ЗНАЧЕНЬ НЕСЕ ЗМІСТ: перше в списку — найдешевше за роздумами.
   Воркер бере саме його, коли переспитує модель після обрізаного JSON.
   Переставиш — повтор почне коштувати більше за першу спробу.
   ─────────────────────────────────────────────────────────────────── */
const EFFORT_OK = [
  { match: /^openai\/gpt-oss/, values: ['low', 'medium', 'high'] },
  { match: /^qwen\/qwen3\.8/,  values: ['none', 'default', 'low', 'medium', 'high'] },
  { match: /^qwen\/qwen3\.6/,  values: ['none', 'default'] }
];

/* Модель без запису в EFFORT_OK не блокуємо: невідома модель — не те саме,
   що модель із відомо чужим значенням. Мовчазна заборона на новій сходинці
   виглядала б як «драбина зламалась», а не як «додай запис». */
const effortOk = (model, value) => {
  const rec = EFFORT_OK.find(e => e.match.test(model));
  return !rec || rec.values.includes(value);
};

/* Список ролей закритий. Невідома роль — це клієнт, а не помилка:
   старий браузер заголовка не шле взагалі, і має працювати далі. */
const ROLES = ['client', 'judge'];

const GROQ = 'https://api.groq.com/openai/v1/chat/completions';

/* Межі. Браузер може просити м'якші значення, але не жорсткіші за ці —
   інакше чужий запит виставить max_completion_tokens 65536 і вигребе
   добову норму токенів за десяток викликів. */
const LIM = {
  maxTokens: 3200,
  msgs: 40,
  chars: 60000,
  temperature: [0, 1.2],
  top_p: [0.1, 1],
  presence_penalty: [-0.5, 1.0]
};

const clamp = (v, [lo, hi], dflt) =>
  (typeof v === 'number' && isFinite(v)) ? Math.min(hi, Math.max(lo, v)) : dflt;

function corsHeaders(origin, env) {
  const allow = String(env.AE_ORIGINS || '').split(',').map(s => s.trim()).filter(Boolean);
  const ok = origin && allow.includes(origin);
  return {
    ok,
    headers: {
      'Access-Control-Allow-Origin': ok ? origin : 'null',
      'Access-Control-Allow-Methods': 'POST, OPTIONS',
      'Access-Control-Allow-Headers': 'Content-Type, x-ae-code, x-ae-role, x-ae-pin',
      'Access-Control-Expose-Headers': 'x-ae-model, x-ae-rung, x-ae-role, retry-after',
      'Access-Control-Max-Age': '86400',
      'Vary': 'Origin'
    }
  };
}

const say = (status, text, extra, cors) => new Response(
  JSON.stringify({ error: { message: text } }),
  { status, headers: { 'Content-Type': 'application/json', ...cors, ...(extra || {}) } }
);

async function handle(request, env) {
  const origin = request.headers.get('Origin');
  const { ok, headers: cors } = corsHeaders(origin, env);

  if (request.method === 'OPTIONS') return new Response(null, { status: 204, headers: cors });
  if (request.method !== 'POST')    return say(405, 'Тільки POST.', null, cors);

  /* Origin. Той самий домен — Origin може не прийти зовсім (Pages Functions),
     тоді пускаємо: same-origin запит уже під нашим контролем. */
  if (origin && !ok) return say(403, 'Запит із чужого домену.', null, cors);

  if (!env.GROQ_KEY) return say(500, 'Ключ моделі не налаштований на сервері.', null, cors);
  /* Кодове слово. Якщо змінної AE_CODE немає — перевірки немає взагалі.
     Браузер шле слово %-кодованим (заголовки HTTP несуть тільки латиницю),
     тому декодуємо перед звіркою. */
  if (env.AE_CODE) {
    let got = request.headers.get('x-ae-code') || '';
    try { got = decodeURIComponent(got); } catch { /* лишаємо як є */ }
    if (got !== env.AE_CODE)
      return say(401, 'Кодове слово мережі не підходить. Перевірте його в налаштуваннях.', null, cors);
  }

  let inBody;
  try { inBody = await request.json(); }
  catch { return say(400, 'Запит не читається.', null, cors); }

  const msgs = inBody && inBody.messages;
  if (!Array.isArray(msgs) || !msgs.length) return say(400, 'Порожній запит.', null, cors);
  if (msgs.length > LIM.msgs)              return say(413, 'Розмова задовга.', null, cors);
  if (JSON.stringify(msgs).length > LIM.chars) return say(413, 'Розмова задовга.', null, cors);

  const rf = inBody.response_format;
  if (!rf || rf.type !== 'json_schema')
    return say(400, 'Запит без схеми відповіді не приймається.', null, cors);

  const roleHdr = request.headers.get('x-ae-role') || '';
  const role = ROLES.includes(roleHdr) ? roleHdr : 'client';

  const base = {
    messages: msgs,
    response_format: rf,
    temperature:       clamp(inBody.temperature,       LIM.temperature,       0.7),
    top_p:             clamp(inBody.top_p,             LIM.top_p,             0.8),
    presence_penalty:  clamp(inBody.presence_penalty,  LIM.presence_penalty,  0.3)
  };

  /* ПІН. Браузер називає НОМЕР сходинки, не модель — назва лишається тут.
     Пін обходить tested навмисно: він і є спосіб перевірити вимкнену
     сходинку, не вмикаючи її для всіх. Запасу в пінованому режимі немає:
     список із однієї сходинки, тож 429 чи зникла модель видно як помилку,
     а не заміну. Немає заголовка → -1 → жодного індексу → звичайна драбина.
     Номер поза межами теж падає у звичайну драбину, і відповідь прийде
     від сходинки 0: розбіжність «просив 7 — відповіла 0» видно на екрані.

     Пін сильніший за роль навмисно: він відповідає на питання «що вміє
     ОЦЯ сходинка», і роль не має права підмінити предмет перевірки.
     Ціна: під піном клієнт і суддя знову в одному відрі, і 429 у розборі
     на довгій розмові — очікувана поведінка режиму перевірки, не поломка. */
  const p = +(request.headers.get('x-ae-pin') || -1);

  /* СТАРТ ЗА РОЛЛЮ. Беремо ввімкнені сходинки і провертаємо список так,
     щоб першою стала та, яка оголосила цю роль своїм стартом. Провертання,
     а не відсікання: запас лишається повним, просто починається з іншого
     місця. Роль без свого старту (або старт вимкнений) іде з початку
     драбини — це не помилка, це просто спільне відро, як було.

     ЧУЖИЙ СТАРТ — ОСТАННІЙ ЗАПАС. Живий прогін показав другий бік
     розведення: коли клієнт вичерпав своє відро і зійшов драбиною, він
     сів рівно на модель судді — і відра злились назад саме в ту хвилину,
     коли навантаження найбільше. Тому сходинка, яку іншa роль назвала
     своїм стартом, відсувається в кінець запасу: падіння перестає
     скасовувати розведення, поки є хоч одна нейтральна сходинка. */
  const enabled = LADDER.filter(r => r.tested);
  const k = enabled.findIndex(r => (r.first || []).includes(role));
  const rotated = k > 0 ? enabled.slice(k).concat(enabled.slice(0, k)) : enabled;
  const mine    = rotated.filter(r => !(r.first || []).some(f => f !== role));
  const foreign = rotated.filter(r =>  (r.first || []).some(f => f !== role));
  const ordered = mine.concat(foreign);

  const rungs = LADDER[p] ? [LADDER[p]] : ordered;
  if (!rungs.length) return say(500, 'Жодна модель не увімкнена на сервері.', null, cors);

  let lastRetry = null, lastMsg = '', skipped = 0;

  for (let i = 0; i < rungs.length; i++) {
    const r = rungs[i];
    /* Стелю токенів беремо з профілю ролі, але браузер може попросити
       МЕНШЕ — більше ні. Роздуми рахуються в цю саму стелю, тому в судді
       вона вища: інакше JSON обірветься на півслові й людина побачить
       «відповідь не читається» замість розбору. */
    const roleCap = r.tokens[role];
    const asked   = inBody.max_completion_tokens;
    const effort  = r.effort[role];

    /* Сходинка з чужим для своєї моделі значенням effort віддасть 400, а
       400 драбиною не сходить — тобто вона не запас, а обрив. Пропускаємо
       її тут, поки запас іще є, і називаємо це вголос, якщо запасу немає.
       Дублює гейт свідомо: цей файл деплоїться руками, гейт над дашбордом
       не стоїть, і мовчазна ручна правка тут коштує всієї драбини. */
    if (!effortOk(r.model, effort)) {
      skipped++;
      lastMsg = 'сходинка налаштована значенням effort, якого модель не приймає';
      continue;
    }

    /* ПОВТОР БЕЗ ЗАЙВИХ РОЗДУМІВ. Обрізаний JSON у режимі схеми — це не
       «гірша відповідь», це відсутність відповіді: постачальник віддає 400
       json_validate_failed. Причина майже завжди одна — роздуми з'їли стелю,
       і на текст не лишилось. Тому переспитуємо ту саму модель найдешевшим
       її режимом роздумів (перше значення в EFFORT_OK), звільняючи всю стелю
       під відповідь.
       Саме ту саму, а не наступну сходинку: 400 драбиною не сходить, і
       прокручувати одну й ту саму багатослівність через усю драбину означає
       заплатити квотою тричі за один і той самий обрив. */
    const cheap  = (EFFORT_OK.find(e => e.match.test(r.model)) || {}).values;
    const tries  = (cheap && cheap[0] !== effort) ? [effort, cheap[0]] : [effort];

    let res = null, text = '';
    for (const eff of tries) {
      const body = {
        ...base,
        model: r.model,
        reasoning_effort: eff,
        reasoning_format: r.reasoning_format,
        max_completion_tokens: Math.min(LIM.maxTokens, roleCap,
          (typeof asked === 'number' && asked > 0) ? asked : roleCap)
      };

      try {
        res = await fetch(GROQ, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + env.GROQ_KEY },
          body: JSON.stringify(body)
        });
      } catch (e) {
        lastMsg = 'мережа: ' + e.message;
        res = null;
        break;
      }

      text = await res.text();
      if (res.ok || !(res.status === 400 && /json_validate_failed/.test(text))) break;
    }

    if (!res) continue;                 // мережа лягла — пробуємо наступну

    if (res.ok) {
      return new Response(text, {
        status: 200,
        headers: {
          'Content-Type': 'application/json',
          ...cors,
          'x-ae-model': r.model,
          /* Номер у ДРАБИНІ, не в перебраному списку. Раніше стояло i —
             індекс серед увімкнених; при двох увімкнених сходинках 0 і 2
             друга називалась «1», і пінований прогін завжди звітував «0».
             Провертання за роллю робить цю різницю щоденною, а не рідкісною:
             у судді перебраний список починається не з нуля взагалі. */
          'x-ae-rung': String(LADDER.indexOf(r)),   // 0 = основна; >0 = резерв
          'x-ae-role': role           // яку роль воркер розпізнав
        }
      });
    }

    /* Далі по драбині йдемо ТІЛЬКИ на квоті й недоступності.
       Помилка змісту (400 — крива схема, задовгий промпт) на всіх моделях
       буде та сама: прокрутити її через драбину означає вигребти квоту
       вчетверо за один баг. Тому — віддаємо одразу. */
    const step = res.status === 429 || res.status >= 500 ||
                 (res.status === 404 && /model|decommission|not.?found/i.test(text));

    lastMsg = text.slice(0, 300);
    if (res.status === 429) lastRetry = res.headers.get('retry-after');

    if (!step) {
      /* Обрив після повтору. Віддавати сюди англійський текст постачальника
         означає показати людині «Failed to generate JSON» замість розбору.
         Код 422 навмисно свій: браузеру не треба знати словник Groq, щоб
         відрізнити цей випадок від решти 400. */
      if (res.status === 400 && /json_validate_failed/.test(text))
        return say(422,
          'Розбір цієї розмови вийшов задовгим і не помістився цілком. ' +
          'Спробуйте «Пройти ще раз» — на коротшій розмові розбір складеться.',
          { 'x-ae-model': r.model }, cors);

      return new Response(text, {
        status: res.status,
        headers: { 'Content-Type': 'application/json', ...cors, 'x-ae-model': r.model }
      });
    }
  }

  /* Драбина скінчилась. Розрізняємо дві причини вголос: квота (чекати) і
     налаштування (чекати марно). Друга виникає тільки після ручної правки
     цього файла — і мовчати про неї означає відправити людину чекати
     хвилину, якої не існує. */
  if (skipped === rungs.length)
    return say(500, 'Драбина моделей налаштована неправильно: жодна сходинка не приймає ' +
                    'свій режим роздумів. Це помилка на сервері, чекати немає сенсу.', null, cors);

  return say(
    503,
    lastRetry
      ? 'Денна норма звернень до моделі вичерпана. Спробуйте пізніше' +
        (lastRetry > 90 ? ' — приблизно за ' + Math.ceil(lastRetry / 60) + ' хв.' : '.')
      : 'Модель зараз недоступна. Спробуйте за кілька хвилин.',
    lastRetry ? { 'retry-after': lastRetry } : null,
    cors
  );
}

export default { fetch: handle };
