#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
x78_curator_term_apply_v1.py — X78 «ТЕРМІН ЗАМКА» (черга, щабель 1, крок 1Б)

В-66 (S65): Оля працює сесіями. Вводити код після кожного повернення в
кураторський режим неприйнятно; лишати відімкненим назавжди небезпечно —
комп'ютер лишається в залі. Вирок: термін у кілька годин.

До X78 `CURATOR.open` — прапорець у пам'яті модуля: помирав із вкладкою і
жив вічно, доки вкладка відкрита. Обидві половини вироку порушені.

ЩО РОБИТЬ
  · `open` стає ОБЧИСЛЮВАНИМ: зараз ще в межах терміну чи вже ні.
  · `grant()` пише мітку «відімкнено до» і в сховище, і в пам'ять модуля.
  · перевірка ЛІНИВА, на читанні. Таймера немає свідомо: коментар цього ж
    вузла прямо забороняє перемальовування посеред роботи — воно змело б
    вердикт, який людина щойно отримала. Замок стуляється на найближчому
    дотику до кураторського екрана, і всі п'ять сторожів уже написані.

РІШЕННЯ, НАЗВАНІ В МІКРОСКОПІ S66
  · Р-2 · дім мітки — `localStorage`, ключ `ae_curator_until`, поруч із
    `ae_pin` / `ae_groq_key` / `ae_net_code`. Дім названо, не вигадано.
  · Д-6 · дім самого ЧИСЛА — константа поруч із вузлом, не в S і не в наборах.
    Чотири години — ЖИВЕ число під device, вироку не має (12.9).
  · Д-3 · смоук `smoke_edit_ui_v1.js:525` рахує ДОВЖИНУ сховища у вікні
    заміру правки. Тому мітка пишеться РІВНО у `grant()` і ніколи ліниво:
    повторний запис наявного ключа довжини не міняє.
  · Р-4 · `EDITKEY.code` на диск НЕ їде. Наслідок названий вголос: після
    перезавантаження в межах терміну навігація відкрита, а публікація
    попросить ключ у власному полі. Це межа В-66, не дефект.
  · запасний дім у пам'яті модуля — на випадок, коли сховище недоступне
    (приватний режим, квота): тоді поведінка та сама, що була до X78.

⚠ A85 (cookbook, том 1): прев'ю відкривається з іншого origin, тож термін
  у прев'ю і на Pages — РІЗНІ сховища. Витіснення сховища під тиском місця
  дає ранній замок, тобто відмову в безпечний бік.
⚠ кутових дужок у коментарях немає свідомо (12.12).

Ідемпотентний: маркер X78-TERM. Повтор — «0 правок», exit 0, той самий md5.
Вхід : AE_WORK_index_X27Q3_v1.html   Вихід: AE_WORK_index_X27Q4_v1.html
"""
import sys, hashlib

MARK = 'X78-TERM'

A_OLD = """/* ── КУРАТОР: одні двері, які на кроці Д переїдуть уперед екрана ───
   Прапорець живе В ПАМʼЯТІ, не в localStorage: закритий застосунок =
   зачинені двері. Це стіна від випадковості, а не безпека — код лежить
   у відкритому config.json і видимий кожному, хто його відкриє. Право
   ПИСАТИ в репозиторій дає інший код (секрет воркера), і змішувати їх
   не можна: тоді запис у дані отримав би кожен, хто прочитав config.

   ⚠ Дім цього прапорця не міняється кроком Д. Міняється лише місце,
   де його питають: сьогодні — всередині екрана Налаштувань, після Д —
   перед ним. Тому підписники, а не render(): відімкнення посеред
   роботи не сміє змести вердикт, який людина щойно отримала. */
const CURATOR = {
  open:false,
  watch:[],                       // очищається на кожному render()
  /* Х22.4: код перевіряє ВОРКЕР (двері в панелі v2, doorCheck) — тут лише «відчинено».
     curatorCode знято разом із полем config.json: одні двері, один код (SPEC «Замок»). */
  grant(){
    this.open = true;
    for(const fn of this.watch) try{ fn(); }catch(_){}
  }
};"""

A_NEW = """/* ── КУРАТОР: одні двері, які на кроці Д переїдуть уперед екрана ───
   X78-TERM (В-66): замок має ТЕРМІН, а не прапорець. До X78 стан жив
   у пам'яті модуля — помирав із вкладкою і водночас тривав вічно, доки
   вкладка відкрита; обидві половини вироку були порушені. Тепер стан —
   мітка «відімкнено до», і `open` її ОБЧИСЛЮЄ.
   Це стіна від випадковості, а не безпека — код лежить у відкритому
   config.json і видимий кожному, хто його відкриє. Право ПИСАТИ в
   репозиторій дає інший код (секрет воркера), і змішувати їх не можна:
   тоді запис у дані отримав би кожен, хто прочитав config.

   ⚠ Перевірка ЛІНИВА, на читанні. Таймера немає свідомо: перемальовування
   посеред роботи змело б вердикт, який людина щойно отримала — тому
   підписники, а не render(). Замок стуляється на найближчому дотику до
   кураторського екрана; сторожі вже стоять у Settings, Editor і ScenCard.

   ⚠ Мітка пишеться РІВНО у grant() і ніколи ліниво: смоук правки рахує
   довжину сховища у своєму вікні заміру, а повторний запис наявного
   ключа довжини не міняє (мікроскоп S66, Д-3).

   ⚠ Ключ запису (EDITKEY) на диск НЕ їде. Наслідок: після перезавантаження
   в межах терміну навігація відкрита, а публікація попросить ключ у
   власному полі. Це межа В-66, не дефект.

   ⚠ A85: прев'ю має інший origin, отже й інше сховище. Витіснення сховища
   під тиском місця дає ранній замок — відмова в безпечний бік.
   живе доки: В-66 не дістав іншого терміну. */
const CURATOR_TERM_MS = 4 * 60 * 60 * 1000;   /* 4 год — ЖИВЕ число під device, вироку не має (12.9) */
const CURATOR_KEY = 'ae_curator_until';
let   CURATOR_MEM = 0;                        /* запасний дім: сховище може бути недоступним */
const CURATOR = {
  watch:[],                       // очищається на кожному render()
  /* Х22.4: код перевіряє ВОРКЕР (двері в панелі v2, doorCheck) — тут лише «відчинено».
     curatorCode знято разом із полем config.json: одні двері, один код (SPEC «Замок»). */
  until(){
    try{ const v = localStorage.getItem(CURATOR_KEY); if(v !== null) return +v || 0; }catch(_){}
    return CURATOR_MEM;
  },
  get open(){ return Date.now() < this.until(); },
  grant(){
    const till = Date.now() + CURATOR_TERM_MS;
    CURATOR_MEM = till;
    try{ localStorage.setItem(CURATOR_KEY, String(till)); }catch(_){}
    for(const fn of this.watch) try{ fn(); }catch(_){}
  }
};"""

EDITS = [('А · замок дістав термін', A_OLD, A_NEW)]


def main():
    if len(sys.argv) != 3:
        print('вжиток: x78_curator_term_apply_v1.py <in.html> <out.html>')
        return 2

    html = open(sys.argv[1], encoding='utf-8').read()
    before = len(html.encode('utf-8'))

    if MARK in html:
        open(sys.argv[2], 'w', encoding='utf-8').write(html)
        print('0 правок — маркер %s уже у файлі (ідемпотентність)' % MARK)
        print('md5 %s · %d б' % (hashlib.md5(html.encode('utf-8')).hexdigest(), before))
        return 0

    if 'X77-DOOR2' not in html:
        print('✗ вхід не той: немає маркера X77-DOOR2 (чекаю X27Q3)')
        return 1

    for name, old, new in EDITS:
        n = html.count(old)
        if n != 1:
            print('✗ якір «%s» знайдено %d разів, очікував 1' % (name, n))
            return 1
        html = html.replace(old, new)

    # ── самоперевірка · вісь 2: на КОРЕКТНОМУ результаті жодна не сміє дати ✗
    if 'open:false' in html.split('const CURATOR =')[1].split('};')[0]:
        print('✗ самоперевірка: старий прапорець лишився поруч із геттером'); return 1
    if 'this.open = true' in html:
        print('✗ самоперевірка: grant досі пише в обчислюване поле'); return 1
    if html.count("get open(){") != 1:
        print('✗ самоперевірка: обчислюваного open немає або їх кілька'); return 1
    if html.count("localStorage.setItem(CURATOR_KEY") != 1:
        print('✗ самоперевірка: мітка пишеться не в одному місці (Д-3)'); return 1
    if "setItem(CURATOR_KEY" not in html.split('grant(){')[1].split('}')[0] + html.split('grant(){')[1][:400]:
        print('✗ самоперевірка: запис мітки живе поза grant()'); return 1
    # п'ять сторожів мусять лишитись на місці — вони і є механізм самозамикання
    if html.count('!CURATOR.open') != 3 or html.count('CURATOR.open ?') != 1:
        print('✗ самоперевірка: сторожі CURATOR.open не на місці'); return 1
    # ключ запису на диск не їде
    if 'EDITKEY' in html.split('const CURATOR =')[1].split('};')[0]:
        print('✗ самоперевірка: ключ запису затесався в замок (Р-4)'); return 1

    after = len(html.encode('utf-8'))
    open(sys.argv[2], 'w', encoding='utf-8').write(html)
    print('%d правок · %+d б' % (len(EDITS), after - before))
    print('md5 %s · %d б' % (hashlib.md5(html.encode('utf-8')).hexdigest(), after))
    return 0


if __name__ == '__main__':
    sys.exit(main())
