def main():
    if not os.path.exists(SRC):
        print("✗ немає вхідного файла: " + SRC)
        return 2
    with open(SRC, encoding="utf-8") as f:
        txt = f.read()

    src_md5 = hashlib.md5(txt.encode("utf-8")).hexdigest()
    print("вхід : %s  md5 %s" % (os.path.basename(SRC), src_md5))

    done, todo = [], []

    # --- 1. редакція в шапці ---
    if "редакція v0.5" in txt:
        done.append("шапка v0.5")
    elif OLD_ED in txt:
        txt = txt.replace(OLD_ED, NEW_ED, 1)
        todo.append("шапка v0.5")
    else:
        print("✗ якір шапки не знайдено")
        return 3

    # --- 2. В-54 у §9 E2 ---
    if MARK_54 in txt:
        done.append("В-54 у §9 E2")
    else:
        if txt.count(ANCHOR_E2) != 1:
            print("✗ якір E2/E3 не унікальний: %d" % txt.count(ANCHOR_E2))
            return 4
        txt = txt.replace(ANCHOR_E2, BLOCK_E2 + ANCHOR_E2, 1)
        todo.append("В-54 у §9 E2")

    # --- 3. §14 у кінець ---
